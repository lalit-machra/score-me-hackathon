'use strict';
// Generates docs/DECISION_EXAMPLES.md from REAL engine output so docs never drift from code.
const fs = require('node:fs');
const path = require('node:path');
const { buildApp } = require('../src/app');

const app = buildApp({ sleep: async () => {} });
const WF = 'employee-onboarding';
const F = '`'.repeat(3);
const base = { fullName: 'Asha Rao', email: 'asha@example.com', role: 'engineer', country: 'IN', startDate: '2026-12-01', yearsExperience: 3, idDocument: 'DOC123' };

const section = (title, blurb, ex, extra = '') => {
  const input = JSON.stringify(ex.input, null, 2);
  const rules = ex.rulesTriggered.length
    ? ex.rulesTriggered.map((r) => `- \`${r.ruleId}\` (${r.stage}) -> **${r.onFail}**: ${r.message}`).join('\n')
    : '_None: every applicable rule passed._';
  const path_ = ex.decisionPath.map((l) => `${l}`).join('\n');
  const hist = ex.stateHistory.map((h) => `${h.seq}. ${h.from || '(new)'} -> **${h.to}** - ${h.reason}`).join('\n');
  return `## ${title}\n\n${blurb}\n\n**Input**\n\n${F}json\n${input}\n${F}\n\n**Result:** \`${ex.state}\` (config ${ex.workflowId} v${ex.configVersion}) - ${ex.reason}\n\n**Rules triggered**\n\n${rules}\n\n**Decision path (audit trace)**\n\n${F}text\n${path_}\n${F}\n\n**State history**\n\n${hist}\n${extra}\n`;
};

(async () => {
  const out = ['# Decision Explanation Examples\n', 'Generated by `npm run examples` from real engine output (`GET /requests/:id/explain`).\n'];

  // 1. Approved with conditional branch
  let r = await app.engine.submit({ workflowId: WF, payload: { ...base, role: 'senior-engineer', yearsExperience: 7, idDocument: 'SR-1001' } });
  out.push(section('1. Approved: senior engineer (conditional background check runs)',
    'Senior roles trigger the extra `background-check` stage; an engineer would skip it.', app.engine.explain(r.instance.id)));

  // 2. Manual review from threshold
  r = await app.engine.submit({ workflowId: WF, payload: { ...base, role: 'senior-engineer', yearsExperience: 3, idDocument: 'SR-1002' } });
  const mr = r.instance.id;
  out.push(section('2. Manual review: threshold rule between floor and target',
    '3 years passes the hard floor (2) but misses the target (5), so a human decides. REJECT would take precedence if both failed.', app.engine.explain(mr)));
  app.engine.resolveReview(mr, { decision: 'APPROVE', reviewer: 'priya', note: 'strong portfolio' });
  out.push(`**After reviewer decision:** \`${app.engine.get(mr).state}\` - ${app.engine.get(mr).history.at(-1).reason}\n`);

  // 3. Rejected
  r = await app.engine.submit({ workflowId: WF, payload: { ...base, country: 'US', idDocument: 'US-1003' } });
  out.push(section('3. Rejected: foreign hire without work permit',
    'The rule only applies when `country != IN` (its `when` guard). The failing comparison is recorded with the actual field value.', app.engine.explain(r.instance.id)));

  // 4. Dependency failure + recovery
  app.services.inject('documentVerification', { failTimes: 3 });
  r = await app.engine.submit({ workflowId: WF, payload: { ...base, idDocument: 'ENG-1004' } });
  const before = app.engine.explain(r.instance.id);
  out.push(section('4a. Dependency failure: parked in RETRY_PENDING',
    'The document service failed 3 times (with exponential backoff). Eligibility results are checkpointed, so only the failed stage is retried.', before));
  await app.engine.retry(r.instance.id);
  out.push(section('4b. After `POST /requests/:id/retry`: resumed and approved',
    'Resumes at `document-verification`; the earlier `eligibility` stage is not re-run.', app.engine.explain(r.instance.id)));

  // 5. Duplicate
  const d = await app.engine.submit({ workflowId: WF, payload: { ...base, idDocument: 'ENG-1004' } });
  out.push(`## 5. Duplicate request\n\nSubmitting the same payload again returns the original decision (\`duplicate: ${d.duplicate}\`, same request id \`${d.instance.id === r.instance.id}\`). No stage runs again and the dependency is not called; the replay is logged as a system event visible in \`explain\`:\n\n${F}json\n${JSON.stringify(app.engine.explain(d.instance.id).systemEvents, null, 2).replace(/"at": "[^"]+",?\n\s*/g, '')}\n${F}\n`);

  fs.writeFileSync(path.join(__dirname, '..', 'docs', 'DECISION_EXAMPLES.md'), out.join('\n'));
  console.log('wrote docs/DECISION_EXAMPLES.md');
})();
